/**
 * Rasterises the PWA icon set and the iOS launch screens from the source SVGs.
 *
 * Both SVGs are the ember point — the same primitive as the logo and the
 * window-band peak marker — so the installed icon and the in-app mark can
 * never drift apart. Re-run after editing either SVG:
 *
 *   node scripts/generate-icons.mjs
 */
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const icons = join(root, "public", "icons");
const splash = join(root, "public", "splash");

/**
 * `ink`, and it is the same value three times over: the ground the app icon is
 * drawn on, the manifest's `background_color`, and the in-app `Splash`. iOS,
 * Android and the browser all show a launch frame and this is the only way
 * they show the same one.
 */
const GROUND = "#0B0C0F";

const OUTPUTS = [
  { src: "icon.svg", out: "icon-192.png", size: 192 },
  { src: "icon.svg", out: "icon-512.png", size: 512 },
  { src: "maskable.svg", out: "maskable-192.png", size: 192 },
  { src: "maskable.svg", out: "maskable-512.png", size: 512 },
  // iOS applies its own rounding and does not support transparency, so the
  // full-bleed source is the right one here too.
  { src: "maskable.svg", out: "apple-touch-icon.png", size: 180 },
];

await mkdir(icons, { recursive: true });

for (const { src, out, size } of OUTPUTS) {
  await sharp(join(icons, src))
    .resize(size, size)
    .png({ compressionLevel: 9 })
    .toFile(join(icons, out));
  console.log(`✓ ${out} (${size}×${size})`);
}

/* ── iOS launch screens ──────────────────────────────────────────────────
   Safari is the one platform that will not compose a launch screen for you.
   Android takes `background_color` plus the icon from the manifest and draws
   it; iOS shows **white** unless it is handed a bitmap whose dimensions match
   the device exactly, which is why an installed PWA so often opens on a white
   flash and then the app.

   Portrait only, and that is a real gap rather than an oversight — the full
   matrix is every device × both orientations, and a phone launched in
   landscape is rare enough that doubling this list to cover it is not worth
   the twenty files. Landscape falls back to white. Said in CLAUDE.md §8.

   The mark is composited at a fixed fraction of the short edge so it lands the
   same optical size on a 375pt phone and a 430pt one. */

const DEVICES = [
  { w: 1320, h: 2868 }, // 16 Pro Max
  { w: 1290, h: 2796 }, // 15/16 Pro Max, 14 Pro Max
  { w: 1206, h: 2622 }, // 16 Pro
  { w: 1179, h: 2556 }, // 15/16, 14 Pro
  { w: 1284, h: 2778 }, // 12/13/14 Pro Max
  { w: 1170, h: 2532 }, // 12/13/14, 15
  { w: 1242, h: 2688 }, // XS Max, 11 Pro Max
  { w: 1125, h: 2436 }, // X, XS, 11 Pro
  { w: 828, h: 1792 }, //  XR, 11
  { w: 750, h: 1334 }, //  SE 2/3, 8
];

await mkdir(splash, { recursive: true });

for (const { w, h } of DEVICES) {
  const mark = Math.round(w * 0.34);
  const rendered = await sharp(join(icons, "icon.svg"))
    .resize(mark, mark)
    .png()
    .toBuffer();

  // The source icon carries its own rounded-rect ground, which is right for an
  // app icon and wrong for a full-bleed launch screen — it would read as a
  // tile floating on a field of the same colour. Extracting the glow and the
  // core means compositing it over an identical ground, so the corners
  // disappear into it.
  await sharp({
    create: {
      width: w,
      height: h,
      channels: 4,
      background: GROUND,
    },
  })
    .composite([{ input: rendered, gravity: "centre" }])
    .png({ compressionLevel: 9 })
    .toFile(join(splash, `launch-${w}x${h}.png`));

  console.log(`✓ splash/launch-${w}x${h}.png`);
}

/**
 * The `<link>` tags, generated with the images.
 *
 * Ten hand-written media queries carrying device pixel ratios is exactly the
 * kind of list that goes stale the first time Apple ships a new size, so it is
 * emitted from the same array the bitmaps come from and imported by the root
 * layout rather than typed out in it.
 */
const links = DEVICES.map(({ w, h }) => {
  // Every device in the list above is @3x except the two @2x ones.
  const ratio = w === 828 || w === 750 ? 2 : 3;
  return {
    media: `(device-width: ${w / ratio}px) and (device-height: ${h / ratio}px) and (-webkit-device-pixel-ratio: ${ratio}) and (orientation: portrait)`,
    href: `/splash/launch-${w}x${h}.png`,
  };
});

await writeFile(
  join(root, "src", "app", "launch-screens.ts"),
  `/**
 * Generated by \`scripts/generate-icons.mjs\` — do not edit by hand.
 *
 * iOS is the only platform that will not compose a launch screen from the
 * manifest, so it gets one bitmap per device size. See the script for why this
 * is portrait-only.
 */
export const LAUNCH_SCREENS = ${JSON.stringify(links, null, 2)} as const;
`,
  "utf8",
);

console.log(`✓ src/app/launch-screens.ts (${links.length} sizes)`);
